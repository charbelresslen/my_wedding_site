// Writes src/app/shared/asset-manifest.ts: the size and checksum of every picture in public/media, exactly as the
// server holds it. The page downloads each picture itself and compares it with this list before showing it (see
// src/app/shared/safe-img.ts), so a picture that arrives damaged is fetched again instead of being painted.
// Runs by itself before every `npm start`, `npm run build` and `npm test`; run it by hand after changing a picture
// if you serve the site some other way.
// The checksum (FNV-1a, 32 bits) must stay identical to src/app/shared/fnv1a.ts.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, extname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const mediaDir = join(root, 'public', 'media');
const outFile = join(root, 'src', 'app', 'shared', 'asset-manifest.ts');
const PICTURES = new Set(['.webp', '.jpg', '.jpeg', '.png', '.gif', '.avif', '.svg']);

function fnv1aHex(bytes) {
  let hash = 0x811c9dc5;
  for (let i = 0; i < bytes.length; i++) {
    hash ^= bytes[i];
    hash = Math.imul(hash, 0x01000193);
  }
  return (hash >>> 0).toString(16).padStart(8, '0');
}

const lines = [];
for (const name of readdirSync(mediaDir).sort()) {
  if (!PICTURES.has(extname(name).toLowerCase())) continue;
  const bytes = readFileSync(join(mediaDir, name));
  lines.push(`  'media/${name}': '${bytes.length}:${fnv1aHex(bytes)}',`);
}

const source = `// GENERATED by tools/make-asset-manifest.mjs (it runs before every start, build and test) - do not edit by hand.

/** "<bytes>:<checksum>" of every picture in public/media, as the server holds it. */
export const ASSET_FINGERPRINTS: Readonly<Record<string, string>> = {
${lines.join('\n')}
};
`;

let current = '';
try {
  current = readFileSync(outFile, 'utf8');
} catch {
  // first run
}
if (current !== source) writeFileSync(outFile, source);
console.log(`asset manifest: ${lines.length} pictures${current === source ? ' (unchanged)' : ' (written)'}`);
